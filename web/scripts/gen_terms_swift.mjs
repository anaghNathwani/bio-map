// Regenerates the iOS copy of the Terms of Service from src/content/terms.js (the single source of truth).
//   npm run terms:swift
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { TERMS_VERSION, TERMS_UPDATED, TERMS_INTRO, TERMS_SECTIONS } = await import(pathToFileURL(path.join(root, 'src/content/terms.js')).href)
const out = path.resolve(root, '../ios/BioMap/BioMap/Views/Onboarding/TermsText.swift')

const q = s => JSON.stringify(s)   // JSON string literals are valid Swift string literals for this text
const blocks = body => body.map(b => Array.isArray(b) ? `.bullets([${b.map(q).join(', ')}])` : `.paragraph(${q(b)})`).join(',\n            ')
const sections = TERMS_SECTIONS.map(s => `        TermsSection(title: ${q(s.title)}, blocks: [\n            ${blocks(s.body)}\n        ])`).join(',\n')

writeFileSync(out, `// GENERATED by web/scripts/gen_terms_swift.mjs from web/src/content/terms.js. Do not edit by hand.
import Foundation

enum TermsBlock {
    case paragraph(String)
    case bullets([String])
}

struct TermsSection: Identifiable {
    let title: String
    let blocks: [TermsBlock]
    var id: String { title }
}

enum TermsText {
    static let version = ${q(TERMS_VERSION)}
    static let updated = ${q(TERMS_UPDATED)}
    static let intro = ${q(TERMS_INTRO)}
    static let sections: [TermsSection] = [
${sections}
    ]
}
`)
console.log('wrote ' + out + ' (' + TERMS_SECTIONS.length + ' sections, version ' + TERMS_VERSION + ')')
